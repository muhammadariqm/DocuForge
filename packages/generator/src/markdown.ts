function statsTable(doc: DFIRDocument): string {
	return [
		"| Component | Count |",
		"|---|---:|",
		`| 🛣️ Routes | **${doc.routes.length}** |`,
		`| 🎮 Controllers | **${doc.controllers.length}** |`,
		`| ⚙️ Services | **${doc.services.length}** |`,
		`| 🧩 Models | **${doc.models.length}** |`,
		`| 🗄️ Database tables | **${doc.database.tables.length}** |`,
		`| 📦 Dependencies | **${doc.dependencies.length}** |`,
	].join("\n");
}

function groupRoutes(doc: DFIRDocument): Map<string, DFIRDocument["routes"]> {
	const groups = new Map<string, DFIRDocument["routes"]>();
	for (const route of doc.routes) {
		const group = routeGroup(route.path);
		if (!groups.has(group)) groups.set(group, []);
		groups.get(group)!.push(route);
	}
	return groups;
}

function routeGroup(path: string): string {
	const value = path.replace(/^\/+/, "");
	if (!value) return "Root";
	const first = value.split("/")[0];
	if (first.toLowerCase() === "api" || first.toLowerCase().startsWith("api-"))
		return "API";
	return humanize(first);
}

function methodBadge(method: string): string {
	const m = method.toUpperCase();
	const icon: Record<string, string> = {
		GET: "🟢",
		POST: "🔵",
		PUT: "🟠",
		PATCH: "🟡",
		DELETE: "🔴",
	};
	return `${icon[m] ?? "⚪"} \`${safe(m)}\``;
}

function humanize(value: string): string {
	return value
		.replace(/([a-z])([A-Z])/g, "$1 $2")
		.replace(/[_-]+/g, " ")
		.replace(/\s+/g, " ")
		.trim()
		.replace(/\b\w/g, (c) => c.toUpperCase());
}

function mermaidIdentifier(value: string): string {
	const result = value.replace(/[^A-Za-z0-9_]/g, "_");
	return /^[A-Za-z_]/.test(result) ? result : `T_${result}`;
}

function mermaidType(type: string): string {
	const value = type.toLowerCase();
	if (value.includes("int")) return "int";
	if (
		value.includes("decimal") ||
		value.includes("float") ||
		value.includes("double")
	)
		return "float";
	if (value.includes("bool")) return "boolean";
	if (value.includes("date") || value.includes("time")) return "datetime";
	return "string";
}

function mermaid(value: string): string {
	return value.replace(/"/g, '\\"').replace(/\r?\n/g, " ");
}

function sanitize(value: string): string {
	const result = value.replace(/[^A-Za-z0-9_]/g, "_");
	return result || "node";
}

function safe(value: string): string {
	return value.replace(/[|`]/g, "\\$&").replace(/\r?\n/g, " ");
}

function percentage(part: number, total: number): number {
	return total ? Math.round((part / total) * 100) : 0;
}

function plural(n: number): string {
	return n === 1 ? "" : "s";
}

function trim(value: string): string {
	return value.replace(/\n+$/g, "");
}
